# Release 0.4 Blueprint — Trusted Platform Operations

## Видение

SPEC76 остаётся простым для заказчика и исполнителя, но получает внутреннее ядро для безопасного управления доступом, процессами, аудитом, знаниями и ИИ-агентами.

## Главная продуктовая формула

> Сложность живёт внутри платформы, а не в голове пользователя.

## Бизнес-ценность

- заказчик размещает заказ без знания внутренней архитектуры;
- исполнитель быстро видит подходящие заказы и откликается;
- владелец платформы управляет исключениями, а не рутиной;
- ИИ-агенты анализируют, рекомендуют и автоматизируют только разрешённые действия;
- значимые решения остаются за Platform Owner (владельцем платформы).

## Входит в релиз

- роли и полномочия;
- интерфейсы по ролям;
- центр внимания владельца;
- управляемые бизнес-процессы;
- аудит действий;
- память подтверждённых решений;
- архитектурная основа специализированных ИИ-агентов.

## Не входит в релиз

- автономные финансовые решения ИИ;
- окончательная блокировка пользователей ИИ;
- самостоятельное изменение правил платформы;
- бесконтрольное самообучение моделей;
- преждевременное выделение отдельного monorepo (монорепозитория) Enterprise Core.
EOF

