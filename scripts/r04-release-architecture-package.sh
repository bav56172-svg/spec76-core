# Architecture Impact Analysis — Release 0.4

## Database (база данных)

Планируются сущности ролей, разрешений, аудита, процессов, случаев, рекомендаций, решений владельца, результатов и версий политик.

## Backend (серверная часть)

Появятся сервисы авторизации, аудита, workflow (бизнес-процессов), knowledge (знаний) и AI operations (ИИ-операций).

## Frontend (пользовательский интерфейс)

Интерфейс разделяется по роли:

- Customer (заказчик): создать заказ, мои заказы, сообщения;
- Contractor (исполнитель): доступные заказы, техника, отклики, сообщения;
- Platform Owner (владелец): Control Center (центр управления), вопросы для решения, риски и отчёты.

## Security (безопасность)

- принцип минимальных полномочий;
- RLS (разграничение доступа на уровне строк);
- запрет привилегированных ключей в клиентском коде;
- человек подтверждает финансовые, юридические, репутационные и критические действия.

## Главный риск

Переусложнение продукта. Любая платформенная возможность обязана проходить UX Gate (проверку удобства): поймёт ли пользователь следующий шаг за пять секунд.
EOF

