## Platform Owner (владелец платформы)

Главный экран — Control Center (центр управления):

- что работает штатно;
- что решено автоматически;
- что требует внимания;
- какие решения рекомендуются;
- какие риски обнаружены.

## Progressive Disclosure (постепенное раскрытие)

Пользователь получает дополнительные возможности только тогда, когда они нужны для текущей задачи.

## UX Gate (проверка удобства)

Экран не готов, если новый пользователь не понимает основное действие за пять секунд.
